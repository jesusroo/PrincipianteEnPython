num1= int(input("ingresa el primer numero "))

op= str(input("ingresa la operacion"))

num2= int(input("ingresa el segundo numero "))

if op=="+":
   print("resultado: ",num1 + num2)
elif op=="-":
   print("resultado: ",num1 - num2)
elif op=="*":
   print("resultado: ",num1 * num2)
elif op=="/":
   print("resultado: ",num1 / num2)
